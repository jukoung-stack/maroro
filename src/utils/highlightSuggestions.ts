/**
 * Returns a list of tailored emotional phrases matching the given title and destination.
 */
export function getEmotionalHighlights(title: string, destination: string): string[] {
  const combined = `${title} ${destination}`.toLowerCase();
  const keywords = extractPlaceKeywords(title, destination);

  const matchedPhrases: string[] = [];

  // Match against categorized phrases
  for (const cat of CATEGORIZED_PHRASES) {
    const isMatched = cat.keywords.some(
      (kw) => combined.includes(kw.toLowerCase()) || keywords.some((k) => k.toLowerCase().includes(kw.toLowerCase()))
    );

    if (isMatched) {
      matchedPhrases.push(...cat.phrases);
    }
  }

  // If matched, take matched ones first, then fill with general
  if (matchedPhrases.length > 0) {
    const unique = Array.from(new Set(matchedPhrases));
    return unique.slice(0, 8);
  }

  return GENERAL_PHRASES;
}

/**
 * Generates an appropriate placeholder for the highlight input
 */
export function getHighlightPlaceholder(title: string, destination: string): string {
  const list = getEmotionalHighlights(title, destination);
  if (list.length > 0) {
    return `예: ${list[0]}`;
  }
  return '예: 은빛 윤슬 위로 부서지는 파도와 온몸을 깨우는 바람';
}
